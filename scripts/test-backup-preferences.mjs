import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";
const moduleUrl = code => `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`;
const compile = async name => ts.transpileModule(await readFile(new URL(`../src/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
let source = await compile("backup-preferences");
for (const name of ["widget-preferences", "medicine-model", "focus-timer-model"]) source = source.replace(`"./${name}"`, JSON.stringify(moduleUrl(await compile(name))));
const { captureBackupPreferences, normalizeBackupPreferences, exportBackupPreferences, applyBackupPreferences, replaceBackupPreferences, BACKUP_PREFERENCE_KEYS } = await import(moduleUrl(source));
const widget = BACKUP_PREFERENCE_KEYS[0];
const timer = "attention-hub.focus-timer.v1";
const skips = "attention-hub.calendar-skips.v1";
const floating = "attention-hub.floating-window.v1.manager";
const values = new Map([[widget, '{"widthMode":"vertical"}'], ["private-cache", "secret"]]);
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
assert.deepEqual(captureBackupPreferences(storage), { [widget]: '{"widthMode":"vertical"}' });
assert.throws(() => normalizeBackupPreferences({ "private-cache": "{}" }));
assert.throws(() => normalizeBackupPreferences({ [widget]: "broken" }));
assert.equal(JSON.parse(exportBackupPreferences({ [widget]: "broken" })[widget]).widthMode, "recommended");
assert.throws(() => normalizeBackupPreferences({ [widget]: "[]" }));
assert.equal(JSON.parse(normalizeBackupPreferences({ [floating]: '{"width":99999}' })[floating]).width, 1600);
assert.deepEqual(JSON.parse(normalizeBackupPreferences({ [floating]: '{"x":20,"y":-10}' })[floating]), { x: 20, y: -10 });
const normalized = normalizeBackupPreferences({ [timer]: '{"elapsedMs":2000,"startedAtUnixMs":1000}', [skips]: '[{"occurrenceId":"live","expiresAt":5000},{"occurrenceId":"old","expiresAt":2000}]' }, 3000);
assert.deepEqual(JSON.parse(normalized[timer]), { elapsedMs: 4000, startedAtUnixMs: null });
assert.deepEqual(JSON.parse(normalized[skips]), [{ occurrenceId: "live", expiresAt: 5000 }]);
replaceBackupPreferences({ [widget]: "malformed original" }, storage);
assert.equal(values.get(widget), "malformed original", "Recovery must preserve exact raw preimages");
assert.equal(values.get("private-cache"), "secret");
const marker = "attention-hub.widget.medicine-panel-upgrade.v1";
const legacyTodo = "attention-hub.later-inbox-preferences.v1";
const legacyNormalized = normalizeBackupPreferences({ [legacyTodo]: '{"dueNotificationsEnabled":true}', [widget]: '{"showMedicinePanel":false}' });
assert.equal(legacyNormalized[marker], "1");
assert.equal(JSON.parse(legacyNormalized["attention-hub.todo-preferences.v1"]).dueNotificationsEnabled, true);
assert.equal(legacyTodo in legacyNormalized, false);
assert.equal(JSON.parse(legacyNormalized[widget]).showMedicinePanel, false);
replaceBackupPreferences({ [legacyTodo]: "original malformed", [marker]: "old" }, storage);
assert.equal(values.get(legacyTodo), "original malformed");
assert.equal(values.get(marker), "old");
replaceBackupPreferences({ [widget]: "malformed original" }, storage);
let calls = 0;
const failing = { ...storage, setItem: (key, value) => { if (++calls === 1) throw new Error("Injected storage failure"); storage.setItem(key, value); } };
assert.throws(() => applyBackupPreferences({ [widget]: "{}" }, failing), /Injected/);
assert.equal(values.get(widget), "malformed original");
calls = 0;
const midFailure = { ...storage, removeItem: key => { if (++calls === 3) throw new Error("Injected removal failure"); storage.removeItem(key); } };
assert.throws(() => applyBackupPreferences({ [widget]: "{}", [timer]: '{"elapsedMs":1}' }, midFailure), /Injected/);
assert.equal(values.get(widget), "malformed original");
assert.equal(values.has(timer), false);
applyBackupPreferences({ [widget]: '{"widthMode":"vertical"}' }, storage);
assert.equal(JSON.parse(values.get(widget)).widthMode, "vertical");
assert.equal(values.get("private-cache"), "secret");
console.log("Backup settings: allowlist, validation, paused timer, expired choices, partial geometry and exact rollback checks passed");
