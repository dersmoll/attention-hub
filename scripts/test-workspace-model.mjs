import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const sourceUrl = new URL("../src/workspace-model.ts", import.meta.url);
const source = await readFile(sourceUrl, "utf8");
const dataPanelSource = await readFile(new URL("../src/WorkspaceDataPanel.tsx", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const model = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputText).toString("base64")}`);
const base = { ownerKind: "list", ownerId: "list-inbox", notes: [], dueOn: null, remindAt: null, notifiedRemindAt: null, completedAt: null, updatedAt: "2026-09-01T08:00:00Z" };
const now = new Date("2026-09-01T12:00:00Z");
const overdue = { ...base, id: "overdue", title: "Overdue", dueOn: "2026-08-31", createdAt: "2026-08-30T08:00:00Z" };
const today = { ...base, id: "today", title: "Today", dueOn: "2026-09-01", createdAt: "2026-08-31T08:00:00Z" };
const futureReminder = { ...base, id: "reminder", title: "Reminder", remindAt: "2026-09-01T18:00:00Z", createdAt: "2026-09-01T08:00:00Z" };
const elapsedReminder = { ...base, id: "elapsed", title: "Elapsed", remindAt: "2026-08-31T18:00:00Z", createdAt: "2026-08-31T08:00:00Z" };
const unscheduled = { ...base, id: "unscheduled", title: "Unscheduled", createdAt: "2026-09-01T09:00:00Z" };
assert.equal(model.isOverdue(overdue, now), true);
assert.equal(model.isDueToday(today, now), true);
assert.equal(model.isReminderToday(futureReminder, now), true);
assert.equal(model.isReminderReached(futureReminder, now), false);
assert.equal(model.isReminderReached(elapsedReminder, now), true);
assert.equal(model.isOverdue(elapsedReminder, now), false);
assert.equal(model.needsAttention(elapsedReminder, now), true);
assert.equal(model.isUnscheduled(unscheduled), true);
assert.equal(model.isActionable(unscheduled, now), false);
assert.equal(model.isVisibleInToday(today, now), true);
const completedToday = { ...today, id: "completed-today", completedAt: now.toISOString() };
const completedYesterday = { ...today, id: "completed-yesterday", completedAt: "2026-08-31T12:00:00Z" };
assert.equal(model.isVisibleInToday(completedToday, now), true);
assert.equal(model.isVisibleInToday(completedYesterday, now), false);
const deferred = model.deferActionItemToTomorrow({ ...today, remindAt: "2026-09-01T15:45:00Z" }, now);
assert.equal(deferred.dueOn, model.localDateKey(new Date(new Date(now).setDate(now.getDate() + 1))));
assert.equal(model.localDateKey(new Date(deferred.remindAt)), deferred.dueOn);
assert.equal(new Date(deferred.remindAt).getHours(), new Date("2026-09-01T15:45:00Z").getHours());
assert.equal(new Date(deferred.remindAt).getMinutes(), 45);
assert.deepEqual(model.sortActionItems([unscheduled, today, overdue]).map(({ id }) => id), ["overdue", "today", "unscheduled"]);
const dueWithLateReminder = { ...base, id: "due-first", title: "Due first", dueOn: "2026-09-02", remindAt: "2026-09-10T09:00:00Z", createdAt: "2026-09-01T10:00:00Z" };
const laterDue = { ...base, id: "later-due", title: "Later due", dueOn: "2026-09-03", createdAt: "2026-09-01T11:00:00Z" };
assert.equal(model.effectiveAt(dueWithLateReminder), Math.min(new Date("2026-09-02T23:59:59.999").getTime(), Date.parse(dueWithLateReminder.remindAt)));
assert.deepEqual(model.sortActionItems([laterDue, dueWithLateReminder]).map(({ id }) => id), ["due-first", "later-due"]);
const snapshot = { projects: [{ id: "active", archivedAt: null }, { id: "archived", archivedAt: "2026-09-01T00:00:00Z" }] };
assert.equal(model.isFromActiveOwner({ ...base, ownerKind: "project", ownerId: "active" }, snapshot), true);
assert.equal(model.isFromActiveOwner({ ...base, ownerKind: "project", ownerId: "archived" }, snapshot), false);
assert.equal(model.isFromActiveOwner(base, snapshot), true);
assert.equal(model.hasUnsavedNoteChanges("typed while saving", "sent"), true);
assert.equal(model.hasUnsavedNoteChanges("sent", "sent"), false);
assert.match(dataPanelSource, /@tauri-apps\/plugin-dialog/);
assert.match(dataPanelSource, /export_workspace_data/);
assert.match(dataPanelSource, /preview_workspace_import/);
assert.match(dataPanelSource, /import_workspace_data/);
assert.match(dataPanelSource, /Replace and import/);
console.log("workspace model tests passed");
